export function getUsernameFromHash(sempahoreIdHash: string): string {
  try {
    const hashBigInt = BigInt(sempahoreIdHash);
    const randomName =
      names[Number((hashBigInt / BigInt(names.length)) % BigInt(names.length))];
    if (!randomName) {
      throw new Error("No random name found");
    }

    return randomName;
  } catch (e) {
    console.debug("Error in useUsernameGenerator", e);
    return "Unknown";
  }
}

